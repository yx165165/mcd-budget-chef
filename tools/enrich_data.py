def main() -> int:
    # ---- (1) 来源标记 ----
    lib_path = os.path.join(DATA, "flavor_tags.json")
    with open(lib_path, "r", encoding="utf-8") as f:
        lib = json.load(f)
    from collections import Counter
    c = Counter()
    for it in lib["items"]:
        s = tag_source(it["name"], it.get("evidence", ""))
        it["source"] = s          # 追加字段
        c[s] += 1
    lib["_meta"]["source_breakdown"] = dict(c)
    with open(lib_path, "w", encoding="utf-8") as f:
        json.dump(lib, f, ensure_ascii=False, indent=2)
    print(f"[1] 来源标记已写入：{dict(c)}")

    # ---- (2) 价格 ----
    pr_path = os.path.join(DATA, "prices_demo.json")
    with open(pr_path, "r", encoding="utf-8") as f:
        pr = json.load(f)
    have = {i["name"] for i in pr["items"]}
    added_p = 0
    for nm, p in PRICES.items():
        if nm not in have:
            pr["items"].append({"name": nm, "price": p})
            added_p += 1
    with open(pr_path, "w", encoding="utf-8") as f:
        json.dump(pr, f, ensure_ascii=False, indent=2)
    print(f"[2] 价格表新增 {added_p} 条 → 共 {len(pr['items'])} 条")

    # ---- (3) 营养 ----
    nu_path = os.path.join(DATA, "nutrition_demo.json")
    with open(nu_path, "r", encoding="utf-8") as f:
        nu = json.load(f)
    have_n = {i["name"] for i in nu["items"]}
    added_n = 0
    for nm, (cal, prot, fat, carb, na) in NUTRI.items():
        if nm not in have_n:
            nu["items"].append({
                "name": nm, "calories": cal, "protein": prot,
                "fat": fat, "carbs": carb, "sodium": na,
            })
            added_n += 1
    with open(nu_path, "w", encoding="utf-8") as f:
        json.dump(nu, f, ensure_ascii=False, indent=2)
    print(f"[3] 营养表新增 {added_n} 条 → 共 {len(nu['items'])} 条")

    # ---- 一致性 ----
    lib_names = {i["name"] for i in lib["items"]}
    pr_names = {i["name"] for i in pr["items"]}
    nu_names = {i["name"] for i in nu["items"]}
    print()
    print(f"口味库 {len(lib_names)} | 价格表 {len(pr_names)} | 营养表 {len(nu_names)}")
    print("口味库有但价格缺:", sorted(lib_names - pr_names) or "无")
    print("口味库有但营养缺:", sorted(lib_names - nu_names) or "无")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
