def tag_source(name: str, evidence: str) -> str:
    for k in OFFICIAL_DISCLOSURE_KEYS:
        if k in name or k in evidence:
            return "official_disclosure"
    for k in OFFICIAL_WEBSITE_KEYS:
        if k in name or k in evidence:
            return "official_website"
    if "官网" in evidence or "mcdonalds.com.cn" in evidence:
        return "official_website"
    return "inferred"


